    return (f'M{cx + rx} {cy} C{cx + rx} {cy + k * ry} {cx + k * rx} {cy + ry} {cx} {cy + ry} '
            f'C{cx - k * rx} {cy + ry} {cx - rx} {cy + k * ry} {cx - rx} {cy} '
            f'C{cx - rx} {cy - k * ry} {cx - k * rx} {cy - ry} {cx} {cy - ry} '
            f'C{cx + k * rx} {cy - ry} {cx + rx} {cy - k * ry} {cx + rx} {cy} Z')


