// Generate the e-paper record/profile coverage ledger from the current contracts.
// This checks registry freshness, not visual fidelity or profile conformance.
//   node tools/build-rendering-profiles.mjs [--check]
import fs from 'node:fs';
import { markdownEngine } from '../parser/jot.mjs';
import { SERVICES } from '../converter/archive.mjs';

const root = new URL('../', import.meta.url);
const read = (name) => fs.readFileSync(new URL(name, root), 'utf8');
const profiles = JSON.parse(read('specification/profiles.json')).profiles;
const spec = read('specification/Jot-Complete-Specification.md');
const section = spec.split('### 5.1 Common record types\n')[1]?.split('#### 5.1.1')[0];
if (!section) throw Error('Cannot find specification section 5.1');
const types = [...new Set([...section.trim().split(/\n\s*\n/)[0].matchAll(/`([a-z][a-z0-9-]*)`/g)].map((m) => m[1]).filter((s) => !s.endsWith('-')))];
if (!types.length) throw Error('The record-type registry is empty');
const code = (value) => `\`${value}\``;
const fields = (items) => items.length ? items.map(code).join(', ') : 'None beyond common fields';
const cell = (text) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const specialized = {
  measurement: ['Metric/value/unit chip when a metric field exists; otherwise ordered fields', 'Complete fields alongside the reading summary; inspect status, time, source, unit, scale and uncertainty before interpreting'],
  scale: ['Definition omitted as a standalone block; chart axes may use its anchors', 'Definition view reachable from its ID or the metric; never hide the only available scale context'],
  sync: ['Bookkeeping omitted from the page', 'Read-only receipt/status inspector; never a request to resend, connect or expose credentials'],
  chart: ['Derived canvas chart, summary and a collapsed numbers table', 'Chart plus labelled data view and source coverage/limit notices; raster capture alone does not export a closed table'],
  query: ['Derived summary/table or a problem notice', 'Paginated results plus query fields and notices; keep original scope and avoid turning a stored query into a service request'],
  palette: ['Named color/hex swatches and remaining fields', 'Named swatches with monochrome labels; asset paths in this branch are not automatically thumbnails'],
  moodboard: ['Asset grid with descriptions/captions/credits and swatches', 'Browseable image list/grid plus all text, color names, credits and attachment actions'],
};
const generic = ['Record type followed by ordered field names and literal values', 'Paged ordered-field view and Inspect/source; activate only explicitly supported links and assets'];
const extensions = {
  documentVariable: ['Host-supplied filename variable', 'syntax.md'],
  musicBrainzLink: ['MusicBrainz identity short reference → link token', 'media-and-links.md'],
  backgroundMediaLink: ['IMDb / YouTube short reference → link token', 'media-and-links.md'],
  spotifyLink: ['Spotify short reference → link token', 'media-and-links.md'],
  colorSpan: ['Inline ink/highlight/strike/underline color presentation', 'syntax.md'],
  mark: ['Highlight', 'syntax.md'],
  ins: ['Underline', 'syntax.md'],
  sup: ['Superscript', 'syntax.md'],
  footnote: ['Footnote definition', 'media-and-links.md'],
  footnoteRef: ['Footnote reference', 'media-and-links.md'],
  center: ['Centered line', 'syntax.md'],
  callout: ['Labelled blockquote metadata', 'syntax.md'],
};
for (const extension of markdownEngine.extensions) if (!extensions[extension]) throw Error(`Add an explicit rendering coverage route for parser extension ${extension}`);
for (const profile of profiles) {
  if (!types.includes(profile.recordType)) throw Error(`Unmapped standard record type ${profile.recordType} in ${profile.id}`);
  if (!fs.existsSync(new URL(`docs/methods/${profile.id}.md`, root))) throw Error(`Missing method guide for ${profile.id}`);
}

const lines = [
  '<!-- Generated by tools/build-rendering-profiles.mjs; edit that source, not this file. -->',
  '# Record, profile and parser-extension coverage',
  '',
  `The current catalogue has **${profiles.length} profiles**, **${types.length} standard record types** and **${markdownEngine.extensions.length} declared parser extensions**.`,
  'This ledger is generated from the profile catalogue, specification section 5.1 and the parser\'s declared extension list.',
  'It complements the [syntax contract](syntax.md), [media and links](media-and-links.md), [integrations](integrations.md)',
  'and [touch/button navigation](navigation.md). It does not assert that a native e-paper reader implements these features.',
  '',
  '## The complete-field rule',
  '',
  'A `method: id@version` value selects a documented profile; it is not a command to launch an integration, change a',
  'device setting, schedule a task, score the writer or run a therapeutic workflow. The current shared preview does not',
  'provide 62 specialized widgets or a complete profile validator. Most records become a type label and field list.',
  '',
  'An e-paper adapter must offer a complete ordered-field/source view alongside any concise visual card. Retain',
  'repeated fields, multiline values, unknown fields, malformed/unparsed lines and source order. Expose IDs, relations',
  'and provenance without making every value clickable. Field values are literal data; embedded code or service names',
  'must not execute. Partial capture remains readable even if profile-required fields are missing.',
  '',
  'The eight common profile fields are `body`, `source`, `relation`, `label`, `author`, `privacy`, `created` and `modified`.',
  'They are available in addition to the catalogue fields below. `privacy`, `consent`, `audience` and `share-with` are',
  'not file encryption or access control. A view-only reader does not silently edit task states, invoke medication',
  'instructions, disclose contact details or create reminders from these fields.',
  '',
  'Touch opens the labelled Inspect/Fields action. Buttons reach it through reader controls, select with up/down and',
  'confirm, page the field list with left/right, then return with Back. Long values get their own paged detail view.',
  'The same route must reach hidden definitions, bookkeeping and fields omitted by compact host previews.',
  '',
  'Required/optional columns below describe the catalogue contract, not validations already performed by the Core',
  'parser. For singleton/repeated-field rules, value ranges and profile-specific caveats, retain the canonical',
  '[catalogue notes](../../specification/profiles.json) and [specification section 13](../../specification/Jot-Complete-Specification.md#13-method-catalogue-and-worked-examples).',
  '',
  '## Standard record types',
  '',
  '| Type | Current shared host preview | E-paper reading contract |',
  '| --- | --- | --- |',
  ...types.map((type) => { const [host, reader] = specialized[type] || generic; return `| ${code(type)} | ${host} | ${reader} |`; }),
  '',
  'The generic path also covers unknown record names and namespaced `x-organization-…` records. Unknown method',
  'versions stay visible with their fields and a support notice; the reader does not apply the nearest known version',
  'as if it were the same contract. Optional rich renderers must retain the generic path.',
  '',
  'The special `measurement` preview is lossy as a record summary: it can omit status, timestamp, bounds, source and',
  'scale. The original record remains in the AST/source. `scale` and `sync` are hidden in the default preview. A raster',
  'of that default page therefore does not establish full-field coverage. See the syntax contract for chart/query',
  'aggregation, truncation and mixed-unit/scale limitations.',
  '',
  '## Every method profile',
  '',
  'Profiles use the record presentation above. This table lists every registered ID/version and every required and',
  'optional catalogue field. Linked method guides provide the practical/research context; their recommendations do',
  'not establish a tested device layout or therapeutic effect. Complete example records are in',
  '[examples-methods.txt](../../specification/examples-methods.txt).',
  '',
  '| Method and research guide | Record type | Profile-required fields | Profile-optional fields |',
  '| --- | --- | --- | --- |',
  ...profiles.map((p) => `| [${code(`${p.id}@${p.version}`)}](../methods/${p.id}.md) · ${cell(p.label)} | ${code(p.recordType)} | ${fields(p.required)} | ${fields(p.optional)} |`),
  '',
  '## Declared parser extensions',
  '',
  'Some extension names are lexer hooks, not AST node types. Media extensions produce ordinary link tokens, and',
  '`callout` is attached to blockquote metadata. The AST schema permits additional node types; this finite list does',
  'not imply that every possible Markdown input or future syntax has been independently certified.',
  '',
  '| Parser extension | Meaning | Rendering and interaction reference |',
  '| --- | --- | --- |',
  ...markdownEngine.extensions.map((name) => `| ${code(name)} | ${extensions[name][0]} | [Contract](${extensions[name][1]}) |`),
  '',
  '## Archive import registry',
  '',
  'These are the canonical archive converter\'s registered sources, not live account clients. Their converted writing',
  'uses the same syntax/media/attachment routes after explicit import. See [integration status and limitations](integrations.md#data-export-converters).',
  'This registry is generated from `converter/archive.mjs`; the remaining provider backlog requires source review',
  'because the project has no single all-provider registry.',
  '',
  '| Converter source ID | Source label | Reader route |',
  '| --- | --- | --- |',
  ...Object.entries(SERVICES).map(([id, label]) => `| ${code(id)} | ${cell(label)} | Saved writing, links and explicitly included assets; no automatic service request |`),
  '',
  '## Maintain and verify coverage',
  '',
  'Run from the repository root:',
  '',
  '```sh',
  'node tools/build-rendering-profiles.mjs',
  'node tools/build-rendering-profiles.mjs --check',
  'node tools/manifest.cjs',
  '```',
  '',
  'The freshness check detects catalogue/registry changes and missing extension routes. It does not verify visual',
  'fidelity, scientific claims, touch/button behavior, media playback, provider APIs or physical device support.',
  'The [rendering overview](README.md) describes acceptance expectations for those separate layers.',
  '',
];
const target = new URL('docs/rendering/profile-coverage.md', root), output = lines.join('\n');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
    console.error('Rendering profile coverage is stale: run node tools/build-rendering-profiles.mjs');
    process.exitCode = 1;
  } else console.log(`Rendering coverage: ${profiles.length} profiles, ${types.length} record types, ${markdownEngine.extensions.length} parser extensions current`);
} else {
  fs.writeFileSync(target, output);
  console.log(`Rendering coverage generated: ${profiles.length} profiles, ${types.length} record types, ${markdownEngine.extensions.length} parser extensions`);
}
